#!/usr/bin/env python3
"""Generate or check a raw-source inventory from Git and OKF source metadata."""
import re
import subprocess
import sys
from pathlib import Path
from urllib.parse import quote, unquote

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'docs/requirements/raw-coverage.md'
PREFIX = 'https://github.com/NikhilVijayakumar/Prati/blob/'

def render():
    tracked = subprocess.check_output(['git', 'ls-files', '-z', '--', 'docs/raw'], cwd=ROOT).decode('utf-8').split('\0')
    sources = {}
    for concept in sorted((ROOT / 'knowledge').rglob('*.md')):
        if concept.name in ('index.md', 'log.md'):
            continue
        for url in re.findall(r'^\s+resource:\s*(https://\S+)', concept.read_text(encoding='utf-8'), re.M):
            if not url.startswith(PREFIX):
                continue
            parts = url[len(PREFIX):].split('/', 1)
            if len(parts) == 2:
                sources.setdefault(unquote(parts[1]), set()).add(concept.relative_to(ROOT).as_posix())
    lines = ['# Raw documentation coverage', '',
             'Generated by `python scripts/knowledge_coverage.py`; run with `--check` to detect drift. This inventories Git-tracked raw files; ignored local reports are excluded. Partial extraction does not mean the whole source has been converted or verified. Audit prompts and templates are reference material, not evidence of an executed audit.', '',
             '| Raw path | Source | Coverage |', '| --- | --- | --- |']
    for source in sorted(filter(None, tracked)):
        relative = source.removeprefix('docs/raw/')
        link = f'[{Path(source).name}](../{quote(source.removeprefix("docs/"), safe="/")})'
        destinations = sorted(sources.get(source, []))
        if destinations:
            status = 'Partial extraction: ' + ', '.join(f'[{Path(x).stem}](../../{quote(x, safe="/")})' for x in destinations)
        elif source.endswith('.svg'):
            status = 'Brand asset retained in raw'
        elif '/data/' in source:
            status = 'Prompt or template indexed; not converted to a knowledge concept'
        elif '/summary/' in source:
            status = 'Historical session status indexed; not durable knowledge'
        else:
            status = 'Indexed only; detailed extraction pending'
        lines.append(f'| `{relative}` | {link} | {status} |')
    return '\n'.join(lines) + '\n'

def main():
    result = render()
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding='utf-8') != result:
            print('FAIL raw coverage is stale; run python scripts/knowledge_coverage.py')
            return 1
        print('PASS raw coverage matches tracked files and concept sources')
    else:
        OUT.write_text(result, encoding='utf-8')
        print('Updated', OUT.relative_to(ROOT))
    return 0

if __name__ == '__main__':
    sys.exit(main())
